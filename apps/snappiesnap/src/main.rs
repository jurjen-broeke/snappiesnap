//! SnappieSnap desktop app.
//!
//! ```text
//! snappiesnap [file.dna] [--sample] [--control PORT]
//! ```
//!
//! Startup problems are reported on stderr with a non-zero exit code; nothing panics. As a last
//! resort the run is wrapped in `catch_unwind`.

// A release build on Windows is a GUI program: no console window opens beside it. (Debug builds
// keep the console for diagnostics; the control channel's port is printed there.)
#![cfg_attr(all(windows, not(debug_assertions)), windows_subsystem = "windows")]

use std::panic::{AssertUnwindSafe, catch_unwind};
use std::process::ExitCode;

use serde_json::json;
use snappiesnap_engine::Session;
use snappiesnap_ui_egui::eframe::{self, egui};
use snappiesnap_ui_egui::{App, LaunchOptions};

const USAGE: &str = "usage: snappiesnap [file.dna] [--sample] [--control PORT] [--record FILE]

  file.dna        open this file
  --sample        open a built-in synthetic sample plasmid
  --control PORT  start the JSON control channel on 127.0.0.1:PORT (0 = any free port)
  --record FILE   write every edit to FILE as a script (replay: snappiesnap-cli run --script)
  --version       print the version";

/// Window and taskbar icon (generated by `cargo xtask icons`). macOS shows it in the Dock, so it
/// gets the tiled macOS variant there; a bundled app's `.icns` looks the same.
#[cfg(target_os = "macos")]
const APP_ICON: &[u8] = include_bytes!("../../../assets/brand/icons/macos/snappiesnap-512.png");
#[cfg(not(target_os = "macos"))]
const APP_ICON: &[u8] =
    include_bytes!("../../../assets/brand/icons/linux/hicolor/256x256/apps/snappiesnap.png");

struct Args {
    file: Option<String>,
    sample: bool,
    options: LaunchOptions,
}

fn parse_args(args: &[String]) -> Result<Option<Args>, String> {
    let mut parsed = Args {
        file: None,
        sample: false,
        options: LaunchOptions::default(),
    };
    let mut it = args.iter();
    while let Some(arg) = it.next() {
        match arg.as_str() {
            "--version" | "-V" => {
                println!("SnappieSnap {}", env!("CARGO_PKG_VERSION"));
                return Ok(None);
            }
            "--help" | "-h" => {
                println!("{USAGE}");
                return Ok(None);
            }
            "--sample" => parsed.sample = true,
            "--control" => {
                let port = it.next().ok_or("--control needs a port")?;
                parsed.options.control_port = Some(
                    port.parse()
                        .map_err(|_| format!("--control: {port:?} is not a port number"))?,
                );
            }
            "--record" => {
                parsed.options.record = Some(it.next().ok_or("--record needs a file")?.clone());
            }
            flag if flag.starts_with('-') => return Err(format!("unknown option {flag}")),
            file => {
                if parsed.file.replace(file.to_string()).is_some() {
                    return Err("only one file can be opened".into());
                }
            }
        }
    }
    Ok(Some(parsed))
}

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    match catch_unwind(AssertUnwindSafe(|| run(&args))) {
        Ok(code) => code,
        Err(_) => {
            eprintln!("error: internal error (this is a bug in SnappieSnap; please report it)");
            ExitCode::FAILURE
        }
    }
}

fn run(args: &[String]) -> ExitCode {
    let args = match parse_args(args) {
        Ok(Some(a)) => a,
        Ok(None) => return ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("error: {e}\n\n{USAGE}");
            return ExitCode::from(2);
        }
    };
    let mut session = Session::new();
    // REBASE, if the user downloaded it before; otherwise the built-in enzymes.
    session.load_enzyme_cache();
    session.load_enzyme_sets();
    if args.sample
        && let Err(e) = snappiesnap_engine::sample::load(&mut session, true)
    {
        eprintln!("error: the sample plasmid failed to load: {e}");
    }
    if let Some(file) = &args.file
        && let Err(e) = session.execute("open", json!({ "path": file, "discard_changes": true }))
    {
        // Start anyway, with the reason visible in the log and on stderr.
        eprintln!("error: {e}");
    }
    let mut viewport = egui::ViewportBuilder::default()
        .with_title(format!("SnappieSnap {}", env!("CARGO_PKG_VERSION")))
        .with_inner_size([1280.0, 820.0])
        .with_min_inner_size([640.0, 400.0]);
    // Reopen at the last size, if Preferences asks for it. Problems with the settings file are
    // reported by the app itself once it runs.
    if let Some(path) = snappiesnap_ui_egui::settings::default_path() {
        let (settings, _) = snappiesnap_ui_egui::settings::load(&path);
        if settings.restore_window
            && let Some(window) = settings.window
        {
            if let Some(size) = window.usable() {
                viewport = viewport.with_inner_size(size);
            }
            if window.maximized {
                viewport = viewport.with_maximized(true);
            }
        }
    }
    match eframe::icon_data::from_png_bytes(APP_ICON) {
        Ok(icon) => viewport = viewport.with_icon(icon),
        Err(e) => eprintln!("warning: the window icon failed to load: {e}"),
    }
    let native = eframe::NativeOptions {
        viewport,
        ..Default::default()
    };
    let mut options = args.options;
    options.remember_settings = true;
    let result = eframe::run_native(
        "SnappieSnap",
        native,
        Box::new(move |cc| Ok(Box::new(App::new(&cc.egui_ctx, session, &options)))),
    );
    match result {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("error: the window could not be opened: {e}");
            ExitCode::FAILURE
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn args(list: &[&str]) -> Result<Option<Args>, String> {
        parse_args(&list.iter().map(|s| s.to_string()).collect::<Vec<_>>())
    }

    #[test]
    fn parses_arguments() {
        let a = args(&["x.dna", "--control", "0", "--sample"])
            .unwrap()
            .unwrap();
        assert_eq!(a.file.as_deref(), Some("x.dna"));
        assert!(a.sample);
        assert_eq!(a.options.control_port, Some(0));
        for bad in [
            &["--control"][..],
            &["--record"],
            &["--control", "abc"],
            &["--control", "70000"],
            &["--nope"],
            &["a.dna", "b.dna"],
        ] {
            assert!(args(bad).is_err(), "{bad:?}");
        }
    }

    #[test]
    fn sample_loads() {
        let mut s = Session::new();
        snappiesnap_engine::sample::load(&mut s, true).unwrap();
        let m = &s.document().unwrap().molecule;
        assert!(m.len() > 2000 && m.features().len() >= 5);
        assert!(!s.document().unwrap().dirty || s.can_undo());
    }

    #[test]
    fn window_icon_decodes() {
        let icon = eframe::icon_data::from_png_bytes(APP_ICON).unwrap();
        assert!(icon.width >= 256 && icon.width == icon.height);
    }
}
